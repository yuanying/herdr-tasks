# shellcheck shell=bash
#
# AGENTS.md / CLAUDE.md の入口を生成する共通処理。
# write-task-agents.sh と write-supervisor-agents.sh から source して使う。

agents_entry_marker='<!-- herdr-tasks generated file.'

# 生成物（マーカー行を持つ通常ファイル）か、まだ存在しないなら成功する。
agents_entry_check_generated() {
  local path="$1"

  if [[ ! -e "${path}" ]]; then
    return 0
  fi

  if [[ -L "${path}" || ! -f "${path}" ]]; then
    echo "conflict: ${path} exists and is not a regular file" >&2
    return 1
  fi

  if [[ "$(head -n 1 "${path}")" != "${agents_entry_marker}"* ]]; then
    echo "conflict: ${path} was not generated by this script" >&2
    return 1
  fi
}

# usage: agents_entry_write <dir> <rendered AGENTS.md>
# 手で書かれたファイルが 1 つでもあれば、何も変更せずに失敗する。
agents_entry_write() {
  local dir="$1" agents_md="$2" has_conflict=0

  agents_entry_check_generated "${dir}/AGENTS.md" || has_conflict=1
  agents_entry_check_generated "${dir}/CLAUDE.md" || has_conflict=1

  if [[ ${has_conflict} -ne 0 ]]; then
    echo "aborting without changes because conflicts were found" >&2
    return 1
  fi

  printf '%s\n' "${agents_md}" >"${dir}/AGENTS.md"
  printf '%s\n\n%s\n' "${agents_entry_marker} AGENTS.md を読み込むためだけのファイルである -->" '@AGENTS.md' \
    >"${dir}/CLAUDE.md"

  echo "wrote: ${dir}/AGENTS.md"
  echo "wrote: ${dir}/CLAUDE.md"
}
